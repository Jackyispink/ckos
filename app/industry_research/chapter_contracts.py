def chapter_contract(chapter_no):
    sections, boundary = CHAPTER_CONTRACTS.get(chapter_no, ('核心结论', '不增加新事实。'))
    return f'建议小节：{sections}。\n本章边界：{boundary}\n每个小节只使用直接支持该问题的资料；资料无关不等于本章有证据。缺少资料时说明具体缺口，允许短章，不以其他章节内容凑字数。'
